-- 10. RPC Functions
create or replace function public.consume_message_quota(p_user_id uuid)
returns setof public.users
language sql
security definer
set search_path = public
as $$
  update public.users
  set free_messages_used = free_messages_used + 1
  where id = p_user_id
    and free_messages_used < free_messages_limit
  returning *;
$$;

create or replace function public.claim_processed_message(
  p_message_id text,
  p_payload jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.processed_messages (message_id, status, payload, attempts)
  values (p_message_id, 'processing', p_payload, 1)
  on conflict (message_id) do update
    set status = 'processing',
        payload = excluded.payload,
        attempts = public.processed_messages.attempts + 1,
        received_at = now(),
        last_error = null
    where public.processed_messages.status = 'failed'
       or (
         public.processed_messages.status = 'processing'
         and public.processed_messages.received_at < now() - interval '10 minutes'
       );
  return found;
end;
$$;

create or replace function public.cleanup_conversation_messages(
  p_keep_count integer default 50
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  deleted_count integer;
begin
  if p_keep_count < 1 then
    raise exception 'p_keep_count must be positive';
  end if;

  with ranked as (
    select id,
      row_number() over (
        partition by user_id
        order by created_at desc, id desc
      ) as message_number
    from public.conversation_messages
  )
  delete from public.conversation_messages messages
  using ranked
  where messages.id = ranked.id
    and ranked.message_number > p_keep_count;

  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

revoke all on function public.consume_message_quota(uuid) from public;
