create table if not exists public.conversation_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  direction text not null check (direction in ('inbound', 'outbound')),
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists conversation_messages_user_created_idx
  on public.conversation_messages (user_id, created_at desc);

alter table public.conversation_messages enable row level security;

do $$
begin
  create policy "backend service role can manage conversation messages"
    on public.conversation_messages for all to service_role using (true) with check (true);
exception
  when duplicate_object then null;
end $$;